local S = require("tests.scen")
local need = require("tools.devload").make(".")
local crypto = need("crypto")

local w = S.world()
local backbone = crypto.newKey()
local eA = w:tesseract({ frequency = 10 })
local eB = w:tesseract({ frequency = 11 })
local mA = w:tesseract({ frequency = 10 })
local mB = w:tesseract({ frequency = 11 })
local eDrive1, eDrive2, mDrive1, mDrive2 = w:diskDrive(), w:diskDrive(), w:diskDrive(), w:diskDrive()
eA:adjacent("south", eDrive1)
eB:adjacent("east", eDrive2)
mA:adjacent("up", mDrive1)
mB:adjacent("west", mDrive2)
eDrive1:insert(w:pocket({ label = "bridge one" }))
eDrive2:insert(w:pocket({ label = "bridge two" }))
w:connect("earth", eA, "tesseract_0")
w:connect("earth", eB, "tesseract_1")
w:connect("earth", eDrive1, "drive_0")
w:connect("earth", eDrive2, "drive_1")
w:connect("mars", mA, "tesseract_0")
w:connect("mars", mB, "tesseract_1")
w:connect("mars", mDrive1, "drive_0")
w:connect("mars", mDrive2, "drive_1")
local earth = S.server(w, { id = 1, realm = "EARTH", dim = "overworld", pos = { 0, 70, 0 }, cable = "earth",
    cfg = S.serverCfg("EARTH", "main", "EARTH", backbone, {}) })
local mars = S.server(w, { id = 2, realm = "MARS", dim = "mars", pos = { 0, 70, 0 }, cable = "mars",
    cfg = S.serverCfg("MARS", "satellite", "EARTH", backbone, {}) })
w:run(10)
S.unlock(w, earth)
S.unlock(w, mars)

mars:typeText("5") w:run(2)
mars:typeText("5") w:run(2)
mars:typeText("a") w:run(2)
S.shot(mars, "MARS ADD BRIDGE")
mars:typeText("2") w:run(2)
S.shot(mars, "MARS SETUP MODE INTRO")
mars:pressKey(S.keys.enter) w:run(3)
S.shot(mars, "MARS WAITING")

earth:typeText("5") w:run(2)
earth:typeText("5") w:run(2)
earth:typeText("a") w:run(2)
earth:typeText("1") w:run(2)
S.shot(earth, "EARTH RUN SETUP INTRO")
earth:pressKey(S.keys.enter) w:run(40)
S.shot(earth, "EARTH AFTER SETUP")
S.shot(mars, "MARS AFTER SETUP")
print("earth paired:", earth:screenText():find("bridge to MARS is set up", 1, true) ~= nil)
print("mars paired:", mars:screenText():find("bridge to EARTH is set up", 1, true) ~= nil)
earth:pressKey(S.keys.enter) w:run(1)
mars:pressKey(S.keys.enter) w:run(1)
w:run(90)
earth:typeText("5") w:run(3)
S.shot(earth, "EARTH BRIDGES AFTER PAIRING")
local t = earth:screenText()
print("bridge running:", t:find("MARS up", 1, true) ~= nil and tonumber(t:match("trips (%d+)") or "0") > 0)
local cfgText = earth:readFile("/.zelnet/config") or ""
print("earth saved the bridge:", cfgText:find("MARS", 1, true) ~= nil)
S.errors(earth, "earth")
S.errors(mars, "mars")
