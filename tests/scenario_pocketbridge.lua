local S = require("tests.scen")
local need = require("tools.devload").make(".")
local crypto = need("crypto")
S.bridgeMedia = "pocket"
local w = S.world()
local earth, mars = S.twoRealms(w, crypto)
w:run(90)
earth:typeText("5") w:run(2)
earth:typeText("5") w:run(3)
S.shot(earth, "EARTH NETWORK OVER POCKET BRIDGE")
local t = earth:screenText()
print("pocket bridge ok:", t:find("MARS up", 1, true) ~= nil and tonumber(t:match("trips (%d+)") or "0") > 0)
S.errors(earth, "earth")
S.errors(mars, "mars")
