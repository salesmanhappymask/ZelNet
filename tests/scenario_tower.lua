local S = require("tests.scen")
local need = require("tools.devload").make(".")
local crypto = need("crypto")

local w = S.world()
local cfg = S.serverCfg("EARTH", "main", "EARTH", crypto.newKey())
local earth = S.server(w, { id = 1, realm = "EARTH", dim = "overworld", pos = { 0, 70, 0 }, cable = "earth", cfg = cfg })
w:run(10)
S.unlock(w, earth)
local tower = w:bitnetTower({ dim = "overworld", pos = { 0, 80, 0 }, complete = false })
w:connect("earth", tower, "bitnet_tower_0")
w:run(5)
earth:typeText("5") w:run(2)
earth:typeText("4") w:run(3)
S.shot(earth, "LINKS WITH INCOMPLETE TOWER")
tower:setComplete(true)
w:run(40)
S.shot(earth, "LINKS AFTER THE TOWER IS FINISHED")
earth:pressKey(S.keys.leftCtrl) w:run(1)
earth:pressKey(S.keys.leftCtrl) w:run(1)
for _ = 1, 5 do earth:pressKey(S.keys.down) end
earth:pressKey(S.keys.enter) w:run(2)
S.shot(earth, "EVENT LOG")
S.errors(earth, "earth")
