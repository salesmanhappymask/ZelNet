local S = require("tests.scen")
local need = require("tools.devload").make(".")
local crypto = need("crypto")

local w = S.world()
local cfg = S.serverCfg("EARTH", "main", "EARTH", crypto.newKey())
local earth = S.server(w, { id = 1, realm = "EARTH", dim = "overworld", pos = { 0, 70, 0 }, cable = "earth", cfg = cfg })
local tower = w:bitnetTower({ dim = "overworld", pos = { 0, 80, 0 } })
w:connect("earth", tower, "bitnet_tower_0")
w:run(10)
S.unlock(w, earth)
local disk = S.provision(w, earth, "1", "far")
local far = w:addComputer({ id = 10, dim = "overworld", pos = { 400, 70, 0 }, color = true })
far:attach("top", w:wirelessModem())
local farTower = w:bitnetTower({ dim = "overworld", pos = { 400, 80, 0 } })
far:attach("back", farTower)
local drive = w:diskDrive()
far:attach("bottom", drive)
drive:insert(disk)
far:boot()
w:run(60)
drive:remove()
w:run(60)
S.shot(far, "FAR CLIENT WITH ITS OWN TOWER")
print("far tower rx:", farTower.repeated, "server tower repeated:", tower.repeated)
S.errors(far, "far")
S.errors(earth, "earth")
