package.path = "./?.lua;" .. package.path
local nativePcall = pcall
local env = require("tests.fakecc").install({ id = 1 })
rawset(_G, "__nativePcall", rawget(_G, "__nativePcall") or nativePcall)
local need = require("tools.devload").make(".")
local registry = need("registry")
local util = need("util")
local crypto = need("crypto")
local kit = require("tests.srvkit").init(env, need)
local t = require("tests.tiny")

local function ctxWith(storage)
    return { log = util.newLogger(50), storage = storage }
end

t.case("add, bind, aliases and lookups", function()
    fs.delete("/.zelnet")
    local reg = registry.new(ctxWith(nil))
    reg:load()
    local rec = assert(reg:add("alice", "client", crypto.newKey()))
    t.eq(rec.status, "pending")
    t.eq(select(2, reg:add("alice", "client", crypto.newKey())), "taken")
    t.eq(select(2, reg:add("Bad Name!", "client", crypto.newKey())), "bad name")
    t.eq(select(2, reg:add("carol", "wizard", crypto.newKey())), "bad role")
    assert(reg:add("bob", "router", crypto.newKey()))
    reg:bind("alice", 42)
    t.eq(reg:byCid(42).name, "alice")
    t.ok(reg:addAlias("alice", "powermon"))
    t.eq(reg:lookup("powermon").name, "alice")
    t.eq(select(2, reg:addAlias("bob", "powermon")), "taken")
    t.eq(select(2, reg:addAlias("bob", "alice")), "taken")
    t.ok(reg:removeAlias("alice", "powermon"))
    t.eq(reg:lookup("powermon"), nil)
    local _, displaced = reg:bind("bob", 42)
    t.eq(displaced and displaced.name, "alice")
    t.eq(reg:byCid(42).name, "bob")
    t.eq(reg:get("alice").cid, nil)
end)

t.case("touch, online window and sweep", function()
    fs.delete("/.zelnet")
    local reg = registry.new(ctxWith(nil))
    reg:load()
    reg.window = 300
    assert(reg:add("alice", "client", crypto.newKey()))
    reg:bind("alice", 7)
    t.eq(reg:touch("alice", { link = "modem:top" }), true)
    t.eq(reg:touch("alice", { link = "modem:top" }), false)
    t.eq(reg:statusOf("alice"), "online")
    local total, online = reg:counts()
    t.eq(total, 1)
    t.eq(online, 1)
    env.advance(301)
    local gone = reg:sweep()
    t.eq(#gone, 1)
    t.eq(reg:statusOf("alice"), "offline")
    reg:revoke("alice")
    t.eq(reg:statusOf("alice"), "revoked")
    t.eq(reg:byCid(7), nil)
end)

t.case("mirror file without storage survives reload", function()
    fs.delete("/.zelnet")
    local reg = registry.new(ctxWith(nil))
    reg:load()
    local key = crypto.newKey()
    assert(reg:add("alice", "client", key))
    reg:bind("alice", 9)
    reg:addAlias("alice", "pm")
    t.ok(fs.exists("/.zelnet/devices.db"), "mirror written")
    local reg2 = registry.new(ctxWith(nil))
    t.eq(reg2:load(), 1)
    t.eq(reg2:get("alice").key, key)
    t.eq(reg2:byCid(9).name, "alice")
    t.eq(reg2:lookup("pm").name, "alice")
end)

t.case("storage preferred, mirror removed after a storage write", function()
    fs.delete("/.zelnet")
    local st = kit.fakeStorage()
    local reg = registry.new(ctxWith(st))
    reg:load()
    assert(reg:add("alice", "client", crypto.newKey()))
    t.ok(st.data["system/devices.db"] ~= nil, "written to storage")
    t.ok(not fs.exists("/.zelnet/devices.db"), "no mirror when storage works")
    local reg2 = registry.new(ctxWith(st))
    reg2:load()
    t.ok(reg2:get("alice") ~= nil)
end)

t.case("storage offline at boot is adopted later without losing records", function()
    fs.delete("/.zelnet")
    local st = kit.fakeStorage()
    local reg = registry.new(ctxWith(st))
    reg:load()
    assert(reg:add("alice", "client", crypto.newKey()))
    st.isReady = false
    local reg2 = registry.new(ctxWith(st))
    reg2:load()
    t.eq(reg2:get("alice"), nil)
    t.ok(reg2.waitStorage)
    assert(reg2:add("bob", "client", crypto.newKey()))
    t.ok(fs.exists("/.zelnet/devices.db"), "mirror while storage offline")
    st.isReady = true
    reg2:flush()
    t.ok(not reg2.waitStorage)
    t.ok(reg2:get("alice") ~= nil, "storage record adopted")
    t.ok(reg2:get("bob") ~= nil, "memory record kept")
    local reg3 = registry.new(ctxWith(st))
    reg3:load()
    t.ok(reg3:get("alice") and reg3:get("bob"), "both persisted")
    t.ok(not fs.exists("/.zelnet/devices.db"), "mirror cleaned")
end)

t.case("corrupt records are ignored", function()
