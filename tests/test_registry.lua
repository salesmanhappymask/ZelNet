    })
    local reg = registry.new(ctxWith(nil))
    t.eq(reg:load(), 1)
    t.eq(reg:get("good").status, "offline")
end)

t.case("touch marks the registry stale, setInfo saves only real changes", function()
    fs.delete("/.zelnet")
    local st = kit.fakeStorage()
    local key = "system/devices.db"
    local reg = registry.new(ctxWith(st))
    reg:load()
    assert(reg:add("alice", "client", crypto.newKey()))
    reg:bind("alice", 5)
    local c = st.counts[key]
    t.eq(c, 2)
    reg:touch("alice", { link = "modem:top", parent = 1 })
    t.ok(reg.stale)
    t.ok(not reg.dirty)
    reg:flush()
    t.eq(st.counts[key], c, "touch saved on a normal flush")
    reg:flush(true)
    t.eq(st.counts[key], c + 1)
    t.eq(st.data[key].alice.parent, 1)
    t.ok(st.data[key].alice.lastSeen ~= nil)
    reg:setInfo("alice", { prog = "1.0.0", hops = 2 })
    t.ok(reg.dirty)
    reg:flush()
    t.eq(st.counts[key], c + 2)
    reg:setInfo("alice", { prog = "1.0.0", hops = 2 })
    t.ok(not reg.dirty, "unchanged info marked dirty")
    reg:flush(true)
    t.eq(st.counts[key], c + 2)
end)

t.case("adopting storage that comes online writes once", function()
    fs.delete("/.zelnet")
    local st = kit.fakeStorage()
    local key = "system/devices.db"
    st.isReady = false
    local reg = registry.new(ctxWith(st))
    reg:load()
    assert(reg:add("bob", "client", crypto.newKey()))
    t.eq(st.counts[key], nil)
    st.isReady = true
    reg:flush()
    t.eq(st.counts[key], 1)
    t.eq(reg.source, "storage")
    t.ok(st.data[key].bob ~= nil)
    t.ok(not fs.exists("/.zelnet/devices.db"))
end)

t.case("real storage: system role used even when another role's disk is missing", function()
    fs.delete("/.zelnet")
    local okMod, storage = pcall(need, "storage")
    if not okMod then
        io.write("      (storage module not present, skipped)\n")
        return
    end
    local cfg = { realm = "EARTH", dataKey = crypto.newKey(), storage = { drives = { mail = "drive_99" } } }
    local log = util.newLogger(50)
    local ctx = { cfg = cfg, log = log, cipher = need("cipher").software(crypto.newKey()) }
    kit.inCo(function()
        local st = storage.new(ctx)
        st:init()
        t.eq(st:ready(), false, "fixture: overall storage should be degraded")
        t.eq(st:ready("system"), true)
        ctx.storage = st
        local reg = registry.new(ctx)
        reg:load()
        local key = crypto.newKey()
        assert(reg:add("alice", "client", key))
        reg:bind("alice", 12)
        t.eq(reg.source, "storage")
        t.ok(not fs.exists("/.zelnet/devices.db"), "plaintext mirror written although system storage works")
        local text = util.readFile("/.zelnet/data/system/devices.db")
        t.ok(text ~= nil, "sealed file missing")
        t.ok(not text:find(key, 1, true), "device key stored in plain text")
        local reg2 = registry.new(ctx)
        t.eq(reg2:load(), 1)
        t.eq(reg2:get("alice").key, key)
        t.eq(reg2:byCid(12).name, "alice")
    end)
end)

t.finish()
