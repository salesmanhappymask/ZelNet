package.path = "./?.lua;" .. package.path
local nativePcall = pcall
local env = require("tests.fakecc").install({ id = 1 })
rawset(_G, "__nativePcall", rawget(_G, "__nativePcall") or nativePcall)
local need = require("tools.devload").make(".")
local kit = require("tests.srvkit").init(env, need)
local directory = need("directory")
local util = need("util")
local t = require("tests.tiny")

local function mainServer(storage)
    fs.delete("/.zelnet")
    kit.reset()
    return kit.newServer({ id = 1, realm = "EARTH", role = "main", storage = storage or kit.fakeStorage() })
end

t.case("claim and lookup on Main", function()
    local srv = mainServer()
    local dir = srv.dir
    local r = dir:apply("MARS", { op = "claim", user = "Bob", realm = "MARS" })
    t.eq(r.ok, true)
    t.eq(r.user, "bob")
    t.eq(dir:userHome("bob"), "MARS")
    t.eq(dir:apply("VENUS", { op = "claim", user = "bob", realm = "VENUS" }).err, "taken")
    t.eq(dir:apply("MARS", { op = "claim", user = "bob", realm = "MARS" }).ok, true, "idempotent")
    t.eq(dir:apply("VENUS", { op = "claim", user = "carl", realm = "MARS" }).err, "denied")
    t.eq(dir:apply("MARS:12", { op = "claim", user = "carl" }).err, "denied")
    t.eq(dir:apply("MARS", { op = "claim", user = "x" }).err, "bad_name")
    t.eq(dir:apply("MARS", { op = "claim", user = "has space" }).err, "bad_name")
    t.eq(dir:apply("EARTH", { op = "claim", user = "dave", realm = "VENUS" }).ok, true, "Main may claim for any realm")
    local look = dir:apply("PLUTO", { op = "lookup", user = "bob" })
    t.eq(look.ok, true)
    t.eq(look.realm, "MARS")
    t.eq(dir:apply("PLUTO", { op = "lookup", user = "nobody" }).err, "unknown_user")
    local list = dir:apply("PLUTO", { op = "list" })
    t.eq(#list.users, 2)
    t.eq(list.users[1].name, "bob")
    t.eq(list.users[2].name, "dave")
    t.eq(dir:apply("VENUS", { op = "release", user = "bob" }).err, "denied")
    t.eq(dir:apply("MARS", { op = "rename", old = "bob", new = "dave" }).err, "taken")
    t.eq(dir:apply("MARS", { op = "rename", old = "bob", new = "robert" }).ok, true)
    t.eq(dir:userHome("robert"), "MARS")
    t.eq(dir:apply("MARS", { op = "release", user = "robert" }).ok, true)
    t.eq(dir:userHome("robert"), nil)
    t.eq(dir:apply("MARS", { op = "bogus" }).err, "bad_request")
    t.eq(dir:apply("MARS", "nope").err, "bad_request")
end)

t.case("local claims on Main and persistence", function()
    local st = kit.fakeStorage()
    local srv = mainServer(st)
    t.eq(srv:claimUser("alice"), true)
    t.eq(srv:userHome("ALICE"), "EARTH")
    t.eq(select(2, srv:claimUser("alice")), nil)
    t.eq(srv:renameUser("alice", "alicia"), true)
    t.eq(select(2, srv:releaseUser("nobody")), "unknown_user")
    local saved = st.data["system/directory.db"]
    t.ok(saved ~= nil, "directory saved to storage")
    t.eq(saved.users.alicia, "EARTH")
    t.ok(saved.ver >= 2)
    local ver, epoch = srv.dir.ver, srv.dir.epoch
    local srv2 = kit.newServer({ id = 1, realm = "EARTH", role = "main", storage = st })
    t.eq(srv2:userHome("alicia"), "EARTH")
    t.eq(srv2.dir.ver, ver)
    t.eq(srv2.dir.epoch, epoch)
    t.eq(srv2.dir.realms.EARTH.serverId, 1)
    t.eq(srv2.dir.realms.EARTH.main, true)
end)

t.case("register replies with the full directory and schedules a push", function()
    local srv = mainServer()
    local dir = srv.dir
    dir:apply("EARTH", { op = "claim", user = "alice", realm = "EARTH" })
    dir.pushDue = false
    local reply = dir:apply("MARS", { op = "register", realm = "MARS", serverId = 7, prog = "1.0.0" })
    t.eq(reply.ok, true)
    t.eq(reply.users.alice, "EARTH")
    t.eq(reply.realms.MARS.serverId, 7)
    t.eq(reply.epoch, dir.epoch)
    t.ok(dir.pushDue, "push scheduled for a new realm")
    dir.pushDue = false
    dir:apply("MARS", { op = "register", realm = "MARS", serverId = 7, prog = "1.0.0" })
    t.ok(not dir.pushDue, "no push when nothing changed")
    t.eq(dir:apply("VENUS", { op = "register", realm = "MARS", serverId = 9 }).err, "denied")
    t.eq(dir:apply("MARS", { op = "push", ver = 999, users = {} }), nil)
    t.eq(dir:userHome("alice"), "EARTH", "Main ignores pushes")
end)

t.case("satellite cache adopts pushes from Main only and works offline", function()
    fs.delete("/.zelnet")
    kit.reset()
    local st = kit.fakeStorage()
    local srv = kit.newServer({ id = 2, realm = "MARS", role = "satellite", mainRealm = "EARTH", storage = st })
    local dir = srv.dir
    t.eq(dir.synced, false)
    dir:apply("EARTH", { op = "push", ver = 5, epoch = "aaaa", users = { bob = "VENUS", ["Bad!"] = "X" }, realms = { VENUS = { serverId = 3 } } })
    t.eq(dir.synced, true)
    t.eq(dir:userHome("bob"), "VENUS")
    t.eq(dir.users["Bad!"], nil)
    t.eq(dir.realms.VENUS.serverId, 3)
    dir:apply("VENUS", { op = "push", ver = 9, epoch = "aaaa", users = {} })
    t.eq(dir:userHome("bob"), "VENUS", "push from a satellite accepted")
    dir:apply("EARTH", { op = "push", ver = 4, epoch = "aaaa", users = {} })
    t.eq(dir:userHome("bob"), "VENUS", "older push accepted")
    dir:apply("EARTH", { op = "push", ver = 1, epoch = "bbbb", users = { carl = "EARTH" } })
    t.eq(dir:userHome("carl"), "EARTH", "new epoch from a reset Main rejected")
    t.eq(dir:userHome("bob"), nil)
    t.eq(dir:apply("EARTH", { op = "claim", user = "x1x" }).err, "not_main")
    t.eq(dir:apply("PLUTO", { op = "lookup", user = "carl" }).realm, "EARTH")
    local srv2 = kit.newServer({ id = 2, realm = "MARS", role = "satellite", mainRealm = "EARTH", storage = st })
    t.eq(srv2:userHome("carl"), "EARTH", "cache survives restart")
    t.eq(srv2.dir.synced, true)
    local ok, err = kit.inCo(function()
        local res = { nil, nil }
        srv2.node:loop(function() res = { srv2:claimUser("dave") } end)
        return res[1], res[2]
    end)
    t.eq(ok, nil)
    t.eq(err, "offline")
end)

