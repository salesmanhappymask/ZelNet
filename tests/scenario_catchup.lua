local S = require("tests.scen")
local need = require("tools.devload").make(".")
local crypto = need("crypto")
local w = S.world()
local earth = S.server(w, { id = 1, realm = "EARTH", dim = "overworld", pos = { 0, 70, 0 }, cfg = S.serverCfg("EARTH", "main", "EARTH", crypto.newKey()) })
w:run(10)
S.unlock(w, earth)
local router = S.device(w, { id = 40, dim = "overworld", pos = { 30, 70, 0 } }, S.provision(w, earth, "2", "relay1"))
local current = router:readFile("/zelnet")
local serverBuild = S.program:match('build = "(%w+)"')
print("router build at install:", current:match('build = "(%w+)"'), "server build:", serverBuild)
router:writeFile("/zelnet", (current:gsub('build = "%w+"', 'build = "0ld0ld00"', 1)))
print("router build written:", router:readFile("/zelnet"):match('build = "(%w+)"'), "size", #router:readFile("/zelnet"))
router:reboot()
w:run(3)
print("router build 3s after reboot:", router:readFile("/zelnet"):match('build = "(%w+)"'))
w:run(27)
print("router build after reboot:", router:readFile("/zelnet"):match('build = "(%w+)"'))
w:run(240)
local after = router:readFile("/zelnet"):match('build = "(%w+)"')
print("router build later:", after)
print("catch up ok:", after == serverBuild)
S.errors(earth, "earth")
S.errors(router, "router")
