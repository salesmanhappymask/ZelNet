package.path = "./?.lua;" .. package.path
local env = require("tests.fakecc").install({ id = 5 })
local need = require("tools.devload").make(".")
local node = need("node")
local config = need("config")
local t = require("tests.tiny")

t.case("server node local request, reply, ping, inbox", function()
    local cfg = config.newServer({ realm = "EARTH" })
    local n = node.new(cfg)
    local got, inboxMsg, pingT
    env.run(function()
        n:loop(function()
            n:listen("echo", function(msg) n:reply(msg, { back = msg.data }) end)
            got = n:request("EARTH", "echo", "hi", 5)
            pingT = n:ping("EARTH", 5)
            n:send("EARTH", "box", { x = 1 })
            inboxMsg = n:receive("box", 5)
        end)
    end, 30)
    t.eq(got and got.back, "hi")
    t.ok(pingT ~= nil, "ping failed")
    t.eq(inboxMsg and inboxMsg.data.x, 1)
end)

t.case("request times out cleanly", function()
    local cfg = config.newServer({ realm = "EARTH" })
    local n = node.new(cfg)
    local body, err
    env.run(function()
        n:loop(function()
            n:listen("slow", function() end)
            body, err = n:request("EARTH", "slow", {}, 2, { retries = 0 })
        end)
    end, 30)
    t.eq(body, nil)
    t.eq(err, "timeout")
end)

t.finish()
