local S = require("tests.scen")
local need = require("tools.devload").make(".")
local w = S.world()
local earth = S.server(w, { id = 1, realm = "EARTH", dim = "overworld", pos = { 0, 70, 0 }, cfg = S.serverCfg("EARTH", "main", "EARTH", need("crypto").newKey()) })
w:run(10)
print("first boot ok:", earth:screenText():find("Server Locked", 1, true) ~= nil)
earth:reboot()
w:run(10)
S.shot(earth, "AFTER REBOOT")
print("reboot ok:", earth:screenText():find("Server Locked", 1, true) ~= nil)
S.errors(earth, "earth")
