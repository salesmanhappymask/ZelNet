local function fresh(extra)
    fs.delete("/.zelnet")
    kit.reset()
    local srv, n = kit.newServer({ id = 1, realm = "EARTH", sides = { "top" }, storage = kit.fakeStorage(), extra = extra })
    return srv, n
end

local function devFrame(n, dcfg, cid, dst, port, body, opts)
    opts = opts or {}
    local pkt = {
        v = 1, id = opts.id or util.newId(), src = opts.src or ("EARTH:" .. cid), dst = dst, port = port, ttl = 24,
        rq = opts.rq, re = opts.re, body = body,
    }
    local w = assert(seal.sealAccess(opts.key or dcfg.deviceKey, pkt, "u", opts.dev or dcfg.name))
    return frame.make(n.cfg.netId, "p", opts.from or cid, opts.to or n.myId, w), pkt
end

local function inject(n, f, link)
    n.inq.push({ f = f, link = link or "modem:top", dist = 5 })
    n:wake()
end

local function downFrames()
    local out = {}
    for _, f in ipairs(kit.framesOf("top", "p")) do
        if f.d.dir == "d" then out[#out + 1] = f end
    end
    return out
end

local function waitDown(count, timeout)
    kit.waitFor(function() return #downFrames() >= count end, timeout or 10)
    return downFrames()
end

local function openFor(dcfg, f)
    return seal.openAccess(dcfg.deviceKey, f.d)
end

local function hello(n, dcfg, cid, opts)
    local f, pkt = devFrame(n, dcfg, cid, "EARTH", "zn.hello", { name = dcfg.name, role = dcfg.role, prog = "1.0.0", cid = cid, hops = 1 }, opts or { rq = true })
    inject(n, f, opts and opts.link)
    return f, pkt
end

t.case("access packet verification and binding", function()
    local srv, n = fresh()
    local dcfg = assert(srv:provision("client", "alice"))
    local online = {}
    srv:on("device_online", function(name) online[#online + 1] = name end)
    kit.runAll({ n }, function()
        local f, pkt = hello(n, dcfg, 42)
        local out = waitDown(1)
        t.eq(#out, 1, "hello reply")
        t.eq(out[1].t, 42)
        t.eq(out[1].d.dev, "alice")
        local reply = assert(openFor(dcfg, out[1]))
        t.eq(reply.re, pkt.id)
        t.eq(reply.body.ok, true)
        t.eq(reply.body.server, 1)
        t.eq(reply.body.realm, "EARTH")
        t.eq(srv.reg:get("alice").cid, 42)
        t.eq(srv.reg:get("alice").prog, "1.0.0")
        t.eq(online[1], "alice")

        kit.clearTx("top")
        inject(n, f)
        sleep(2)
        t.eq(#downFrames(), 0, "replay answered")
        t.eq(srv.counters.replays, 1)

        local bad = devFrame(n, dcfg, 42, "EARTH", "zn.hello", {}, { rq = true, key = crypto.newKey() })
        inject(n, bad)
        sleep(2)
        t.eq(#downFrames(), 0, "bad key answered")
        t.ok(srv.counters.accessBad >= 1)

        local spoof = devFrame(n, dcfg, 43, "EARTH", "zn.hello", {}, { rq = true })
        inject(n, spoof)
        sleep(2)
        t.eq(#downFrames(), 0, "spoofed cid answered")
        t.eq(srv.counters.spoofed, 1)

        local unknown = devFrame(n, dcfg, 44, "EARTH", "zn.hello", {}, { rq = true, dev = "mallory" })
        inject(n, unknown)
        sleep(2)
        t.eq(srv.counters.unknownDevice, 1)

        local notMine = devFrame(n, dcfg, 42, "EARTH", "zn.hello", {}, { rq = true, to = 99 })
        inject(n, notMine)
        sleep(2)
        t.eq(#downFrames(), 0, "frame for another computer answered")

        srv:revoke("alice")
        hello(n, dcfg, 42)
        sleep(2)
        t.eq(#downFrames(), 0, "revoked answered")
        t.eq(srv.counters.revoked, 1)
        t.eq(srv:devices()[1].status, "revoked")
    end)
end)

