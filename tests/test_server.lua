t.case("downstream routing direct, via router and flooding", function()
    local srv, n = fresh()
    local a = assert(srv:provision("client", "alice"))
    local b = assert(srv:provision("endpoint", "bob"))
    kit.runAll({ n }, function()
        hello(n, a, 42)
        hello(n, b, 43, { rq = true, from = 50 })
        waitDown(2)
        t.eq(srv.reg:get("bob").parent, 50)
        t.eq(srv.reg:get("alice").parent, 1)
        kit.clearTx("top")

        n:send("EARTH:42", "app", { x = 1 })
        local out = waitDown(1)
        t.eq(out[1].t, 42)
        local p = assert(openFor(a, out[1]))
        t.eq(p.body.x, 1)
        t.eq(p.src, "EARTH")
        t.eq(p.port, "app")
        kit.clearTx("top")

        n:send("EARTH:bob", "app", { y = 2 })
        out = waitDown(1)
        t.eq(out[1].t, 50, "via router")
        p = assert(openFor(b, out[1]))
        t.eq(p.body.y, 2)
        t.eq(p.dst, "EARTH:43", "dst rewritten to the computer id")
        kit.clearTx("top")

        inject(n, (devFrame(n, a, 42, "EARTH:bob", "app", { z = 3 })))
        out = waitDown(1)
        t.eq(out[1].t, 50)
        p = assert(openFor(b, out[1]))
        t.eq(p.src, "EARTH:42")
        t.eq(p.body.z, 3)
        kit.clearTx("top")

        env.advance(700)
        sleep(6)
        kit.clearTx("top")
        n:send("EARTH:42", "app", { w = 4 })
        out = waitDown(1)
        t.eq(out[1].t, nil, "flooded without a route")
        t.eq(assert(openFor(a, out[1])).body.w, 4)
    end)
end)

