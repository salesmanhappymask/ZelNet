t.case("pub/sub delivery, retained values and local subscribers", function()
    local srv, n = fresh()
    local a = assert(srv:provision("client", "alice"))
    local b = assert(srv:provision("endpoint", "bob"))
    local c = assert(srv:provision("endpoint", "carol"))
    local localGot = {}
    kit.runAll({ n }, function()
        hello(n, a, 42)
        hello(n, b, 43)
        hello(n, c, 44)
        waitDown(3)
        n:subscribe("power.mars", function(topic, data, src) localGot[#localGot + 1] = { topic, data, src } end)
        kit.clearTx("top")
        local f, pkt = devFrame(n, a, 42, "EARTH", "zn.ps", { op = "sub", topic = "power.*" }, { rq = true })
        inject(n, f)
        local out = waitDown(1)
        local r = assert(openFor(a, out[1]))
        t.eq(r.re, pkt.id)
        t.eq(r.body.ok, true)
        kit.clearTx("top")

        inject(n, (devFrame(n, b, 43, "EARTH", "zn.ps", { op = "pub", topic = "power.mars", data = { stored = 5 }, retain = true })))
        out = waitDown(1)
        t.eq(#out, 1)
        t.eq(out[1].t, 42)
        local m = assert(openFor(a, out[1]))
        t.eq(m.port, "zn.ps")
        t.eq(m.body.op, "msg")
        t.eq(m.body.topic, "power.mars")
        t.eq(m.body.data.stored, 5)
        t.eq(m.body.from, "EARTH:43")
        kit.waitFor(function() return #localGot > 0 end, 5)
        t.eq(localGot[1][1], "power.mars")
        t.eq(localGot[1][2].stored, 5)
        t.eq(localGot[1][3], "EARTH:43")
        kit.clearTx("top")

        inject(n, (devFrame(n, b, 43, "EARTH", "zn.ps", { op = "pub", topic = "power.mars", data = { stored = 6 } })))
        sleep(2)
        t.eq(#downFrames(), 0, "second publish inside a second was delivered")
        t.eq(srv.counters.rateLimited, 1)

        inject(n, (devFrame(n, c, 44, "EARTH", "zn.ps", { op = "sub", topic = "power.mars" })))
        out = waitDown(1)
        t.eq(out[1].t, 44)
        m = assert(openFor(c, out[1]))
        t.eq(m.body.op, "msg")
        t.eq(m.body.data.stored, 5, "retained value")
        t.eq(m.body.retained, true)
        kit.clearTx("top")

        inject(n, (devFrame(n, c, 44, "EARTH", "zn.ps", { op = "sub", topic = "power.mars" })))
        sleep(2)
        t.eq(#downFrames(), 0, "renewal resent the retained value")

        inject(n, (devFrame(n, a, 42, "EARTH", "zn.ps", { op = "unsub", topic = "power.*" })))
        sleep(2)
        n:publish("power.mars", { stored = 7 })
        kit.waitFor(function() return #downFrames() >= 1 end, 5)
        out = downFrames()
        t.eq(#out, 1)
        t.eq(out[1].t, 44)
        t.eq(assert(openFor(c, out[1])).body.from, "EARTH")
        kit.clearTx("top")

        inject(n, (devFrame(n, a, 42, "EARTH", "zn.ps", { op = "msg", topic = "power.mars", data = { stored = 666 } })))
        sleep(2)
        for _, g in ipairs(localGot) do t.neq(g[2].stored, 666, "spoofed msg delivered") end

        local fwdBefore = #localGot
        srv:psOp("MARS", { op = "fwd", topic = "power.mars", data = { stored = 9 }, from = "MARS:3", retain = true })
        kit.waitFor(function() return #localGot > fwdBefore end, 5)
        t.eq(localGot[#localGot][2].stored, 9)
        t.eq(srv.topics["power.mars"].retained.from, "MARS:3")
        t.eq(srv:psOp("EARTH:42", { op = "fwd", topic = "power.mars", data = 1 }), nil)
    end)
end)

t.case("name registration and resolution", function()
    local srv, n = fresh()
    local a = assert(srv:provision("client", "alice"))
    local b = assert(srv:provision("client", "bob"))
    kit.runAll({ n }, function()
        hello(n, a, 42)
        hello(n, b, 43)
        waitDown(2)
        kit.clearTx("top")
        local f = devFrame(n, a, 42, "EARTH", "zn.name", { op = "register", name = "powermon" }, { rq = true })
        inject(n, f)
        local r = assert(openFor(a, waitDown(1)[1]))
        t.eq(r.body.ok, true)
        t.eq(r.body.addr, "EARTH:powermon")
        kit.clearTx("top")

        inject(n, (devFrame(n, b, 43, "EARTH", "zn.name", { op = "register", name = "powermon" }, { rq = true })))
        r = assert(openFor(b, waitDown(1)[1]))
        t.eq(r.body.ok, false)
        t.eq(r.body.err, "taken")
        kit.clearTx("top")

        inject(n, (devFrame(n, b, 43, "EARTH", "zn.name", { op = "register", name = "earth" }, { rq = true })))
        r = assert(openFor(b, waitDown(1)[1]))
        t.eq(r.body.err, "taken", "server name")
        kit.clearTx("top")

        inject(n, (devFrame(n, b, 43, "EARTH", "zn.name", { op = "resolve", name = "powermon" }, { rq = true })))
        r = assert(openFor(b, waitDown(1)[1]))
        t.eq(r.body.addr, "EARTH:42")
        kit.clearTx("top")

        inject(n, (devFrame(n, b, 43, "EARTH:powermon", "app", { hi = 1 })))
        local out = waitDown(1)
        t.eq(out[1].t, 42)
        t.eq(assert(openFor(a, out[1])).body.hi, 1)
        kit.clearTx("top")

        t.eq(n:register("svc"), true)
        inject(n, (devFrame(n, b, 43, "EARTH:svc", "app", { local1 = true })))
        local msg = n:receive("app", 5)
        t.ok(msg ~= nil, "server name delivery")
        t.eq(msg.src, "EARTH:43")
        t.eq(n:resolve("EARTH:svc"), "EARTH:1")
        t.eq(n:resolve("EARTH:powermon"), "EARTH:42")
        local _, err = n:register("powermon")
        t.eq(err, "taken")

        inject(n, (devFrame(n, a, 42, "EARTH", "zn.name", { op = "release", name = "powermon" }, { rq = true })))
        r = assert(openFor(a, waitDown(1)[1]))
        t.eq(r.body.ok, true)
        t.eq(srv.reg:lookup("powermon"), nil)
    end)
end)

