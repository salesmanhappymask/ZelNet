        inject(n, notMine)
        sleep(2)
        t.eq(#downFrames(), 0, "frame for another computer answered")

        srv:revoke("alice")
        hello(n, dcfg, 42)
        sleep(2)
        t.eq(#downFrames(), 0, "revoked answered")
        t.eq(srv.counters.revoked, 1)
        t.eq(srv:devices()[1].status, "revoked")
    end)
end)

