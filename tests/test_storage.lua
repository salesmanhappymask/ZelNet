t.case("drive roles, labels, offline and disk events", function()
    clean()
    local d1 = drive("drive_1", "disk", { label = "old" })
    local d2 = drive("drive_2", "disk2", {})
    local ctx = newCtx({ dataKey = crypto.newKey(), drives = { accounts = "drive_1", mail = "drive_2" } })
    local events = {}
    ctx.emit = function(ev, a) events[#events + 1] = ev .. ":" .. tostring(a) end
    local st = storage.new(ctx)
    local ok = st:init()
    t.ok(ok)
    t.eq(d1.label, "ZelNet-Accounts")
    t.eq(d2.label, "ZelNet-Mail")
    t.ok(st:write("accounts", "users.db", { x = 1 }))
    t.ok(fs.exists("/disk/accounts/users.db"))
    t.ok(st:write("chat", "global.db", { x = 1 }))
    t.ok(fs.exists("/.zelnet/data/chat/global.db"))
    d2.disk = false
    t.ok(st:onDiskEvent("disk_eject", "drive_2"))
    t.ok(not st:ready())
    t.ok(not st:ready("mail"))
    t.ok(st:ready("accounts"))
    local wok, werr = st:write("mail", "a/index.db", {})
    t.eq(wok, nil)
    t.eq(werr, "storage offline")
    t.ok(not st:onDiskEvent("disk", "drive_9"), "unrelated drive ignored")
    d2.disk = true
    st:onDiskEvent("disk", "drive_2")
    t.ok(st:ready())
    t.ok(util.contains(events, "storage_offline:mail"))
    t.ok(util.contains(events, "storage_online:mail"))
    local info = st:info()
    t.eq(#info, 5)
    t.eq(info[1].role, "accounts")
    t.eq(info[1].drive, "drive_1")
    t.eq(info[1].label, "ZelNet-Accounts")
    t.eq(info[1].files, 1)
    t.ok(info[1].present)
    t.eq(info[3].label, "local")
end)

