local function drive(name, mount, opts)
    opts = opts or {}
    local d = { name = name, mount = mount, disk = opts.disk ~= false, floppy = opts.floppy ~= false, label = opts.label }
    env.setPeripheral(name, { type = "drive", methods = {
        isDiskPresent = function() return d.disk end,
        hasData = function() return d.disk and d.floppy end,
        getMountPath = function() if d.disk and d.floppy then return d.mount end return nil end,
        getDiskLabel = function() if d.disk then return d.label end return nil end,
        setDiskLabel = function(l) d.label = l end,
    } })
    return d
end

local function clean()
    local all = env.files()
    local gone = {}
    for path in pairs(all) do gone[#gone + 1] = path end
    for _, path in ipairs(gone) do all[path] = nil end
    fs.delete("/.zelnet")
    fs.delete("/disk")
    fs.delete("/disk2")
    fs.delete("/disk3")
end

local function newCtx(opts)
    opts = opts or {}
    local cfg = { storage = { drives = opts.drives or {} }, dataKey = opts.dataKey }
    local log = util.newLogger(50)
    return { cfg = cfg, log = log, cipher = opts.cipher }
end

t.case("local fallback with software cipher round trip", function()
    clean()
    local key = crypto.newKey()
    local ctx = newCtx({ dataKey = key, cipher = cipher.software(crypto.newKey()) })
    local st = storage.new(ctx)
    local ok, problems = st:init()
    t.ok(ok, table.concat(problems or {}, ";"))
    t.ok(st:ready())
    t.ok(st:ready("mail"))
    t.ok(st:write("accounts", "users.db", { alice = { name = "alice" } }))
    local raw = util.readFile("/.zelnet/data/accounts/users.db")
    t.ok(raw ~= nil, "file written under local dir")
    t.ok(not raw:find("alice", 1, true), "file is sealed")
    t.ok(raw:find("zs=1", 1, true) ~= nil, "software sealing used")
    local back = st:read("accounts", "users.db", nil)
    t.eq(back.alice.name, "alice")
    t.ok(st:exists("accounts", "users.db"))
    t.ok(st:write("mail", "alice/index.db", { n = 1 }))
    t.ok(st:write("mail", "alice/bob.db", { seq = 1 }))
    local names = st:list("mail", "alice")
    t.eq(#names, 2)
    t.eq(names[1], "bob.db")
    t.ok(st:delete("mail", "alice/bob.db"))
    t.eq(#st:list("mail", "alice"), 1)
    t.eq(st:read("mail", "alice/bob.db", "dflt"), "dflt")
end)

