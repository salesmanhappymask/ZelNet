t.case("hardware style cipher uses zs 2 and rejects a planted plaintext file", function()
    clean()
    local soft = cipher.software(crypto.newKey())
    local hw = { kind = "hardware", encrypt = soft.encrypt, decrypt = soft.decrypt, present = function() return true end }
    local ctx = newCtx({ cipher = hw, dataKey = crypto.newKey() })
    local st = storage.new(ctx)
    st:init()
    t.ok(st:write("accounts", "users.db", { a = 1 }))
    local raw = util.readFile("/.zelnet/data/accounts/users.db")
