    st2:init()
    local all = st2:auditTail(1000)
    t.eq(#all, 300)
    t.eq(all[300].action, "act11")
end)

t.case("audit while the audit disk is missing is merged later", function()
    clean()
    local d = drive("drive_1", "disk", {})
    local ctx = newCtx({ dataKey = crypto.newKey(), drives = { audit = "drive_1" } })
    local st = storage.new(ctx)
    st:init()
    st:audit("a", "first", nil, nil, true)
    d.disk = false
    st:onDiskEvent("disk_eject", "drive_1")
    st:audit("a", "second", nil, nil, true)
    d.disk = true
    st:onDiskEvent("disk", "drive_1")
    st:flush()
    local st2 = storage.new(ctx)
    st2:init()
    local tail = st2:auditTail(5)
    t.eq(#tail, 2)
    t.eq(tail[1].action, "second")
end)

