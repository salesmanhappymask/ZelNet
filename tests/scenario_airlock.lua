local S = require("tests.scen")
local need = require("tools.devload").make(".")
local crypto = need("crypto")
local w = S.world()
local cfg = S.serverCfg("EARTH", "main", "EARTH", crypto.newKey(), { airlocks = true })
local earth = S.server(w, { id = 1, realm = "EARTH", dim = "overworld", pos = { 0, 70, 0 }, cable = "earth", cfg = cfg })
w:run(10)
S.unlock(w, earth)

local function writeAirlockDisk()
    local fl = w:floppy({ label = "blank" })
    earth.provDrive:insert(fl)
    w:run(1)
    earth:typeText("2") w:run(2)
    earth:typeText("n") w:run(2)
    S.shot(earth, "NEW DEVICE")
    earth:typeText("4") w:run(2)
    S.shot(earth, "PICK DRIVE")
    earth:pressKey(S.keys.enter) w:run(2)
    S.shot(earth, "CONFIRM")
    earth:pressKey(S.keys.enter) w:run(5)
    S.shot(earth, "WRITTEN")
    earth:pressKey(S.keys.enter) w:run(1)
    earth:pressKey(S.keys.leftCtrl) w:run(1)
    return earth.provDrive:remove()
end

local function airlockComputer(id, x, disk)
    local c = w:addComputer({ id = id, dim = "overworld", pos = { x, 70, 0 }, color = true })
    c:attach("top", w:wirelessModem())
    local d = w:diskDrive()
    c:attach("bottom", d)
    d:insert(disk)
    c:setRedstoneInput("back", true)
    c:boot()
    w:run(4)
    return c, d
end

local doorDisk = writeAirlockDisk()
print("disk files:", doorDisk:readFile("airlock") ~= nil, doorDisk:readFile("startup") ~= nil)
local door, doorDrive = airlockComputer(70, 10, doorDisk)
S.shot(door, "DOOR FIRST START")
door:typeText("1") w:run(1)
door:pressKey(S.keys.enter) w:run(1)
door:typeText("6") w:run(1)
door:typeText("3") w:run(1)
door:typeText("1") w:run(1)
door:typeText("2") w:run(8)
doorDrive:remove()
S.shot(door, "DOOR RUNNING")

local sensorDisk = writeAirlockDisk()
local sensor, sensorDrive = airlockComputer(71, 14, sensorDisk)
sensor:typeText("2") w:run(1)
sensor:pressKey(S.keys.enter) w:run(1)
sensor:typeText("6") w:run(1)
sensor:typeText("1") w:run(8)
sensorDrive:remove()
S.shot(sensor, "SENSOR RUNNING")

w:run(10)
print("door open with air:", door.rsOut.left == 15)
sensor:setRedstoneInput("back", false)
w:run(5)
print("door sealed when the sensor loses air:", door.rsOut.left == 0)
S.shot(door, "DOOR AFTER VENT")
sensor:setRedstoneInput("back", true)
w:run(4)
print("door waits for the chamber to settle:", door.rsOut.left == 0)
w:run(15)
print("door open again:", door.rsOut.left == 15)

local router = S.device(w, { id = 40, dim = "overworld", pos = { 55, 70, 0 } }, S.provision(w, earth, "2", "relay1"))
earth:pressKey(S.keys.leftCtrl) w:run(1)
w:run(20)
local farDoor, farDoorDrive = airlockComputer(80, 100, writeAirlockDisk())
farDoor:typeText("1") w:run(1)
farDoor:pressKey(S.keys.backspace) farDoor:pressKey(S.keys.backspace) farDoor:pressKey(S.keys.backspace) farDoor:pressKey(S.keys.backspace) farDoor:pressKey(S.keys.backspace) farDoor:pressKey(S.keys.backspace)
farDoor:typeText("dock2-A") farDoor:pressKey(S.keys.enter) w:run(1)
farDoor:typeText("6") w:run(1)
farDoor:typeText("3") w:run(1)
farDoor:typeText("1") w:run(1)
farDoor:typeText("2") w:run(15)
farDoorDrive:remove()
local farSensor, farSensorDrive = airlockComputer(81, 104, writeAirlockDisk())
farSensor:typeText("2") w:run(1)
for _ = 1, 6 do farSensor:pressKey(S.keys.backspace) end
farSensor:typeText("dock2-C") farSensor:pressKey(S.keys.enter) w:run(1)
farSensor:typeText("6") w:run(1)
farSensor:typeText("1") w:run(15)
farSensorDrive:remove()
S.shot(farDoor, "FAR DOOR")
print("far door linked through the router:", farDoor:screenText():find("#40 linked", 1, true) ~= nil)
print("far door open with air:", farDoor.rsOut.left == 15)
farSensor:setRedstoneInput("back", false)
w:run(8)
print("far door sealed through the router:", farDoor.rsOut.left == 0)
farSensor:setRedstoneInput("back", true)
w:run(25)
print("far door open again:", farDoor.rsOut.left == 15)
farSensor:setRedstoneInput("back", false)
w:run(8)
print("a leak seals only its own airlock:", farDoor.rsOut.left == 0 and door.rsOut.left == 15)
farSensor:setRedstoneInput("back", true)
w:run(25)
print("both open after the leak is fixed:", door.rsOut.left == 15 and farDoor.rsOut.left == 15)
earth:typeText("7") w:run(3)
S.shot(earth, "AIRLOCKS PAGE")
local page = earth:screenText()
earth:pressKey(S.keys.leftCtrl) w:run(1)
earth:shutdown()
w:run(2)
sensor:setRedstoneInput("back", false)
w:run(9)
print("door seals from its sensor with the server down:", door.rsOut.left == 0)
sensor:setRedstoneInput("back", true)
w:run(2)
local cfg2 = S.serverCfg("EARTH", "main", "EARTH", crypto.newKey(), { airlocks = true })
local rebuilt = S.server(w, { id = 5, realm = "EARTH", dim = "overworld", pos = { 2, 70, 0 }, cable = "earth2", cfg = cfg2 })
w:run(20)
S.shot(door, "DOOR AFTER SERVER REBUILT")
print("relinked to the new server:", door:screenText():find("#5 linked", 1, true) ~= nil)
print("airlock ok:", door.rsOut.left == 15 and page:find("dock", 1, true) ~= nil and door:readFile("/startup") ~= nil)
print("relay ok:", page:find("dock2", 1, true) ~= nil and farDoor.rsOut.left == 15)
S.errors(earth, "earth")
