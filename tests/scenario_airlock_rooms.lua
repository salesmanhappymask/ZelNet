local S = require("tests.scen")
local need = require("tools.devload").make(".")
local crypto = need("crypto")

local w = S.world()
local cfg = S.serverCfg("EARTH", "main", "EARTH", crypto.newKey(), { airlocks = true })
local earth = S.server(w, { id = 1, realm = "EARTH", dim = "overworld", pos = { 0, 70, 0 }, cable = "earth", cfg = cfg })
w:run(10)
S.unlock(w, earth)

local function writeAirlockDisk()
    local fl = w:floppy({ label = "blank" })
    earth.provDrive:insert(fl)
    w:run(1)
    earth:typeText("2") w:run(2)
    earth:typeText("n") w:run(2)
    earth:typeText("4") w:run(2)
    earth:pressKey(S.keys.enter) w:run(2)
    earth:pressKey(S.keys.enter) w:run(5)
    earth:pressKey(S.keys.enter) w:run(1)
    earth:pressKey(S.keys.leftCtrl) w:run(1)
    return earth.provDrive:remove()
end

local function airlockComputer(id, x)
    local c = w:addComputer({ id = id, dim = "overworld", pos = { x, 70, 0 }, color = true })
    c:attach("top", w:wirelessModem())
    local d = w:diskDrive()
    c:attach("bottom", d)
    d:insert(writeAirlockDisk())
    c:setRedstoneInput("back", true)
    c:boot()
    w:run(4)
    return c, d
end

local function clear(c, n)
    for _ = 1, n do c:pressKey(S.keys.backspace) end
end

local south, southDrive = airlockComputer(80, 10)
south:typeText("3") w:run(1)
clear(south, 6)
south:typeText("South") south:pressKey(S.keys.enter) w:run(1)
south:typeText("6") w:run(1)
south:typeText("1") w:run(1)
south:typeText("1") w:run(8)
southDrive:remove()
S.shot(south, "ROOM SENSOR")
print("room sensor screen:", south:screenText():find("ROOM SENSOR", 1, true) ~= nil and south:screenText():find("South", 1, true) ~= nil)

local hall, hallDrive = airlockComputer(81, 12)
hall:typeText("2") w:run(1)
hall:pressKey(S.keys.enter) w:run(1)
hall:typeText("6") w:run(1)
hall:typeText("1") w:run(1)
hall:typeText("1") w:run(8)
hallDrive:remove()

local door, doorDrive = airlockComputer(82, 14)
door:typeText("1") w:run(1)
door:pressKey(S.keys.enter) w:run(4)
S.shot(door, "ROOM QUESTION")
print("room question lists South:", door:screenText():find("South", 1, true) ~= nil)
door:typeText("4") w:run(1)
door:typeText("6") w:run(1)
door:typeText("3") w:run(1)
door:typeText("1") w:run(1)
door:typeText("2") w:run(1)
door:typeText("1") w:run(10)
doorDrive:remove()

local vault, vaultDrive = airlockComputer(83, 16)
vault:typeText("4") w:run(1)
vault:pressKey(S.keys.enter) w:run(4)
vault:typeText("4") w:run(1)
vault:typeText("3") w:run(1)
vault:typeText("3") w:run(1)
vault:typeText("2") w:run(1)
vault:typeText("1") w:run(10)
vaultDrive:remove()
S.shot(vault, "SECURITY DOOR")
print("security door screen:", vault:screenText():find("SECURITY DOOR", 1, true) ~= nil and vault:screenText():find("South: air ok", 1, true) ~= nil and vault:screenText():find("North:", 1, true) ~= nil)

w:run(15)
S.shot(door, "DOOR")
print("door open with both areas holding:", door.rsOut.left == 15)
print("door shows hallway and room:", door:screenText():find("Hallway", 1, true) ~= nil and door:screenText():find("South: air ok", 1, true) ~= nil)
print("vault open:", vault.rsOut.left == 15)

earth:typeText("7") w:run(3)
S.shot(earth, "AIRLOCKS PAGE")
local page = earth:screenText()
print("console lists the room sensor and the door's room:", page:find("[room sensor]", 1, true) ~= nil and page:find("> South", 1, true) ~= nil and page:find("[security]", 1, true) ~= nil)
earth:pressKey(S.keys.leftCtrl) w:run(1)

south:setRedstoneInput("back", false)
w:run(8)
S.shot(door, "DOOR WHEN SOUTH LOSES AIR")
print("door seals when the South sensor reads no air:", door.rsOut.left == 0)
print("door says why:", door:screenText():find("room South: no oxygen", 1, true) ~= nil)
print("vault closes too:", vault.rsOut.left == 0)
south:setRedstoneInput("back", true)
w:run(30)
print("door reopens after South recovers:", door.rsOut.left == 15)
print("vault reopens:", vault.rsOut.left == 15)

earth:shutdown()
w:run(2)
south:setRedstoneInput("back", false)
w:run(10)
print("with the server down the door seals from the South sensor:", door.rsOut.left == 0)
print("and so does the vault:", vault.rsOut.left == 0)

S.errors(earth, "earth")
S.errors(south, "south")
S.errors(hall, "hall")
S.errors(door, "door")
S.errors(vault, "vault")
