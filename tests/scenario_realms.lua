local S = require("tests.scen")
local need = require("tools.devload").make(".")
local crypto = need("crypto")

local w = S.world()
local backbone = crypto.newKey()

local eSend = w:tesseract({ frequency = 1 })
local eRecv = w:tesseract({ frequency = 2 })
local mSend = w:tesseract({ frequency = 2 })
local mRecv = w:tesseract({ frequency = 1 })
local eSendDrive, eRecvDrive, mSendDrive, mRecvDrive = w:diskDrive(), w:diskDrive(), w:diskDrive(), w:diskDrive()
eSend:adjacent("north", eSendDrive)
eRecv:adjacent("north", eRecvDrive)
mSend:adjacent("north", mSendDrive)
mRecv:adjacent("north", mRecvDrive)
eSendDrive:insert(w:floppy({ label = "earth-mars" }))
mSendDrive:insert(w:floppy({ label = "mars-earth" }))
w:connect("earth", eSend, "tesseract_0")
w:connect("earth", eRecv, "tesseract_1")
w:connect("earth", eSendDrive, "drive_0")
w:connect("earth", eRecvDrive, "drive_1")
w:connect("mars", mSend, "tesseract_0")
w:connect("mars", mRecv, "tesseract_1")
w:connect("mars", mSendDrive, "drive_0")
w:connect("mars", mRecvDrive, "drive_1")

local function bridgeTo(peer)
    return { { peer = peer, sendTess = "tesseract_0", sendDrive = "drive_0", sendDir = "north", recvTess = "tesseract_1", recvDrive = "drive_1", recvDir = "north" } }
end

local earth = S.server(w, { id = 1, realm = "EARTH", dim = "overworld", pos = { 0, 70, 0 }, cable = "earth",
    cfg = S.serverCfg("EARTH", "main", "EARTH", backbone, { bridges = bridgeTo("MARS") }) })
local mars = S.server(w, { id = 2, realm = "MARS", dim = "mars", pos = { 0, 70, 0 }, cable = "mars",
    cfg = S.serverCfg("MARS", "satellite", "EARTH", backbone, { bridges = bridgeTo("EARTH") }) })

w:run(10)
S.unlock(w, earth)
S.unlock(w, mars)
w:run(120)
earth:typeText("5") w:run(2)
S.shot(earth, "EARTH NETWORK")
earth:pressKey(S.keys.leftCtrl) w:run(1)
mars:typeText("5") w:run(2)
S.shot(mars, "MARS NETWORK")
mars:pressKey(S.keys.leftCtrl) w:run(1)
S.errors(earth, "earth")
S.errors(mars, "mars")

local eDisk = S.provision(w, earth, "1", "eclient")
local mDisk = S.provision(w, mars, "1", "mclient")
local ec = S.device(w, { id = 10, dim = "overworld", pos = { 20, 70, 0 } }, eDisk)
local mc = S.device(w, { id = 20, dim = "mars", pos = { 20, 70, 0 } }, mDisk)
S.shot(ec, "EARTH CLIENT")
S.shot(mc, "MARS CLIENT")

local function create(c, user)
    c:typeText("2") w:run(2)
    c:typeText(user) c:pressKey(S.keys.tab) c:typeText("hunter22") c:pressKey(S.keys.tab) c:typeText("hunter22") c:pressKey(S.keys.enter)
    w:run(30)
end
create(ec, "bob")
create(mc, "alice")
S.shot(ec, "BOB HOME")
S.shot(mc, "ALICE HOME")

ec:typeText("2") w:run(2)
S.shot(ec, "COMPOSE")
ec:typeText("alice") ec:pressKey(S.keys.enter)
w:run(20)
S.shot(ec, "CONVERSATION")
ec:typeText("hello from earth") ec:pressKey(S.keys.enter)
w:run(60)
S.shot(ec, "AFTER SEND")
w:run(60)
S.shot(mc, "ALICE AFTER DELIVERY")
mc:typeText("1") w:run(5)
S.shot(mc, "ALICE INBOX")
mc:pressKey(S.keys.enter) w:run(15)
S.shot(mc, "ALICE THREAD")
mc:typeText("hi bob, mars here") mc:pressKey(S.keys.enter) w:run(90)
S.shot(ec, "BOB SEES REPLY")
S.errors(ec, "eclient")
S.errors(mc, "mclient")
S.errors(earth, "earth")
S.errors(mars, "mars")
