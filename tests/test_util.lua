package.path = "./?.lua;" .. package.path
require("tests.shim").install()
local need = require("tools.devload").make(".")
local util = need("util")
local t = require("tests.tiny")

t.case("fmtFixed and friends", function()
    t.eq(util.fmtFixed(78.40000000007132, 1), "78.4")
    t.eq(util.fmtFixed(-39.5567, 2), "-39.56")
    t.eq(util.fmtFixed(1, 1), "1.0")
    t.eq(util.fmtFixed(0.05, 1), "0.1")
    t.eq(util.fmtTrim(2.50, 2), "2.5")
    t.eq(util.fmtTrim(3.0, 1), "3")
    t.eq(util.fmtAmount(5676162), "5.68M")
    t.eq(util.fmtAmount(300000000), "300M")
    t.eq(util.fmtAmount(391448), "391K")
    t.eq(util.fmtBytes(125000), "122.1K")
    t.eq(util.fmtDuration(3725), "1h 2m")
    t.eq(util.fmtStamp(24 * 3 + 8.5), "D3 08:30")
end)

t.case("wrapText", function()
    local lines = util.wrapText("the quick brown fox jumps", 10)
    t.eq(lines[1], "the quick")
    t.eq(lines[2], "brown fox")
    t.eq(lines[3], "jumps")
    local hard = util.wrapText("abcdefghijklmnop", 5)
    t.eq(hard[1], "abcde")
    t.eq(hard[4], "p")
    local para = util.wrapText("a\n\nb", 5)
    t.eq(#para, 3)
    t.eq(para[2], "")
end)

t.case("addresses", function()
    local a = util.parseAddress("mars:42")
    t.eq(a.realm, "MARS")
    t.eq(a.id, 42)
    local b = util.parseAddress("EARTH:PowerMon")
    t.eq(b.name, "powermon")
    t.eq(util.normAddress("earth"), "EARTH")
    t.eq(util.normAddress("*"), "*")
    t.eq(util.parseAddress("bad realm!"), nil)
    t.eq(util.parseAddress("EARTH:"), nil)
    t.eq(util.parseAddress("TOOLONGREALMNAME"), nil)
    t.ok(util.topicMatches("power.*", "power.mars"))
    t.ok(not util.topicMatches("power.*", "powerx"))
    t.ok(util.validTopic("power.mars"))
    t.ok(not util.validTopic("bad topic"))
end)

t.case("queue and seen set", function()
    local q = util.newQueue()
    q.push(1)
    q.push(2)
    t.eq(q.size(), 2)
    t.eq(q.pop(), 1)
    t.eq(q.pop(), 2)
    t.eq(q.pop(), nil)
    local s = util.newSeenSet(100, 3)
    t.eq(s.check("a"), false)
    t.eq(s.check("a"), true)
    s.check("b")
    s.check("c")
    s.check("d")
    t.eq(s.has("a"), false)
    t.eq(s.has("d"), true)
end)

t.finish()
